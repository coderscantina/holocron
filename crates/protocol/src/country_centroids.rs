/// Centroid of an upper-case ISO 3166-1 alpha-2 country code, as tenths of a degree
/// (latitude, longitude). `None` for a code without one.
pub fn centroid(code: &str) -> Option<(i16, i16)> {
    CENTROIDS
        .binary_search_by(|(known, ..)| (*known).cmp(code))
        .ok()
        .map(|i| (CENTROIDS[i].1, CENTROIDS[i].2))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn centroids_are_found_by_upper_case_code() {
        assert_eq!(centroid("AT"), Some((475, 146)));
        assert_eq!(centroid("NZ").map(|(lat, _)| lat < 0), Some(true));
        assert_eq!(centroid("XX"), None);
        assert_eq!(centroid("at"), None);
        assert!(CENTROIDS.windows(2).all(|pair| pair[0].0 < pair[1].0));
    }
}
