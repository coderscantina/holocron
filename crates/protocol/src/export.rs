//! Generates the TypeScript contract and the OpenAPI document from the registry, and checks
//! committed copies for drift. Output is sorted, so an unchanged registry changes no byte.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::{fs, io};

use schemars::generate::SchemaSettings;
use schemars::{JsonSchema, SchemaGenerator};
use serde_json::{Map, Value, json};

use crate::registry::{Access, Kind, OperationInfo, Reauth, ShareReach, TypeInfo};
use crate::{config, country_centroids, envelope, errors, limits, operations, setup};

/// First line of every file this module writes besides the ts-rs type files, which carry
/// their own "Do not edit" note.
pub const MARKER: &str = "// Generated by holocron-protocol: cargo run -p holocron-protocol --bin export-types. Do not edit this file manually.";

/// `apps/web/src/generated` in this repository.
pub fn default_web_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../apps/web/src/generated")
}

/// `crates/protocol/openapi.json` in this repository.
pub fn default_openapi_path() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("openapi.json")
}

/// Everything the exporter writes.
pub struct Output {
    /// File name to contents, for the web app's generated directory.
    pub web: BTreeMap<String, String>,
    pub openapi: String,
}

/// Types the browser needs that no operation references.
fn extra_types() -> [TypeInfo; 21] {
    [
        TypeInfo::of::<errors::ApiErrorBody>(),
        TypeInfo::of::<envelope::CommandKey>(),
        TypeInfo::of::<envelope::CommandMeta>(),
        TypeInfo::of::<envelope::SnapshotMeta>(),
        TypeInfo::of::<config::RuntimeConfig>(),
        TypeInfo::of::<operations::explorations::LiveFrame>(),
        TypeInfo::of::<setup::SetupTokenArgs>(),
        TypeInfo::of::<setup::SetupCheck>(),
        TypeInfo::of::<setup::SetupAdminArgs>(),
        TypeInfo::of::<setup::SetupSignInArgs>(),
        TypeInfo::of::<setup::SetupStatus>(),
        TypeInfo::of::<setup::SetupInspectArgs>(),
        TypeInfo::of::<setup::SetupInspection>(),
        TypeInfo::of::<setup::SetupRunArgs>(),
        TypeInfo::of::<setup::SetupImportProgress>(),
        TypeInfo::of::<setup::SetupDiscardArgs>(),
        TypeInfo::of::<setup::SetupBackups>(),
        TypeInfo::of::<setup::SetupRestoreInspectArgs>(),
        TypeInfo::of::<setup::SetupRestoreInspection>(),
        TypeInfo::of::<setup::SetupRestoreArgs>(),
        TypeInfo::of::<setup::SetupRestoreProgress>(),
    ]
}

fn ts_config(dir: &Path) -> ts_rs::Config {
    // Revisions and timestamps stay below 2^53, so they are plain numbers in the browser.
    ts_rs::Config::new()
        .with_out_dir(dir)
        .with_large_int("number")
}

fn sorted_operations() -> Vec<&'static OperationInfo> {
    let mut ops: Vec<_> = operations::all().collect();
    ops.sort_by_key(|op| op.name);
    ops
}

pub fn generate() -> io::Result<Output> {
    let scratch = scratch_dir()?;
    let result = generate_in(&scratch);
    let _ = fs::remove_dir_all(&scratch);
    result
}

fn generate_in(scratch: &Path) -> io::Result<Output> {
    let cfg = ts_config(scratch);
    let ops = sorted_operations();

    for info in ops
        .iter()
        .flat_map(|op| [op.args, op.result])
        .chain(extra_types())
    {
        (info.export)(&cfg).map_err(io::Error::other)?;
    }

    let mut web = BTreeMap::new();
    for entry in fs::read_dir(scratch)? {
        let path = entry?.path();
        let name = path
            .file_name()
            .and_then(|n| n.to_str())
            .unwrap_or_default()
            .to_owned();
        web.insert(name, fs::read_to_string(&path)?);
    }

    let type_files: Vec<String> = web.keys().cloned().collect();
    web.insert(
        "commands.ts".into(),
        operation_map(&cfg, &ops, Kind::Command),
    );
    web.insert("queries.ts".into(), operation_map(&cfg, &ops, Kind::Query));
    web.insert("errors.ts".into(), error_list());
    web.insert("limits.ts".into(), limit_list());
    web.insert("countries.ts".into(), country_list());
    web.insert("index.ts".into(), index(&type_files));

    Ok(Output {
        web,
        openapi: openapi(&ops),
    })
}

fn scratch_dir() -> io::Result<PathBuf> {
    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_nanos())
        .unwrap_or_default();
    let dir = std::env::temp_dir().join(format!("holocron-export-{}-{nanos}", std::process::id()));
    fs::create_dir_all(&dir)?;
    Ok(dir)
}

fn operation_map(cfg: &ts_rs::Config, ops: &[&OperationInfo], kind: Kind) -> String {
    let (interface, names, grantable) = match kind {
        Kind::Command => ("Commands", "commandNames", "keyGrantableCommands"),
        Kind::Query => ("Queries", "queryNames", "keyGrantableQueries"),
    };
    let ops: Vec<_> = ops.iter().filter(|op| op.kind == kind).collect();

    let mut imports: Vec<String> = ops
        .iter()
        .flat_map(|op| [(op.args.ts_name)(cfg), (op.result.ts_name)(cfg)])
        .collect();
    imports.sort();
    imports.dedup();

    let mut out = format!("{MARKER}\n");
    for name in &imports {
        let _ = writeln!(out, "import type {{ {name} }} from './{name}'");
    }
    let _ = writeln!(out, "\nexport interface {interface} {{");
    for op in &ops {
        let reauth = match kind {
            Kind::Command => format!("; reauth: '{}'", reauth_name(op.policy.reauth)),
            Kind::Query => String::new(),
        };
        let _ = writeln!(
            out,
            "  '{}': {{ args: {}; result: {}; access: '{}'{reauth} }}",
            op.name,
            (op.args.ts_name)(cfg),
            (op.result.ts_name)(cfg),
            access_name(op.access)
        );
    }
    let _ = writeln!(out, "}}\n");
    let listed: Vec<String> = ops.iter().map(|op| format!("'{}'", op.name)).collect();
    let _ = writeln!(
        out,
        "export const {names} = [{}] as const satisfies readonly (keyof {interface})[]",
        listed.join(", ")
    );
    let keyed: Vec<String> = ops
        .iter()
        .filter(|op| op.policy.key_grantable)
        .map(|op| format!("'{}'", op.name))
        .collect();
    let _ = writeln!(
        out,
        "\n/** Operations an API key may hold in its grants. */\nexport const {grantable} = [{}] as const satisfies readonly (keyof {interface})[]",
        keyed.join(", ")
    );
    if kind == Kind::Query {
        let preset: Vec<String> = operations::api_keys::READ_ANALYTICS_PRESET
            .iter()
            .map(|name| format!("'{name}'"))
            .collect();
        let _ = writeln!(
            out,
            "\n/** The \"Read analytics\" grants for agent keys. */\nexport const readAnalyticsPreset = [{}] as const satisfies readonly (typeof keyGrantableQueries[number])[]",
            preset.join(", ")
        );
    }
    out
}

fn reauth_name(reauth: Reauth) -> &'static str {
    match reauth {
        Reauth::Never => "never",
        Reauth::Always => "always",
        Reauth::Handler => "handler",
    }
}

fn access_name(access: Access) -> &'static str {
    match access {
        Access::Anonymous => "anonymous",
        Access::Person => "person",
    }
}

fn error_list() -> String {
    let codes: Vec<String> = errors::ErrorCode::ALL
        .iter()
        .map(|code| format!("'{}'", code.as_str()))
        .collect();
    format!(
        "{MARKER}\nimport type {{ ErrorCode }} from './ErrorCode'\n\n\
         export const errorCodes = [{}] as const satisfies readonly ErrorCode[]\n",
        codes.join(", ")
    )
}

fn limit_list() -> String {
    let mut out = format!("{MARKER}\n");
    for (name, doc, value) in limits::NUMBERS {
        let _ = writeln!(
            out,
            "\n/** {} */\nexport const {name} = {value}",
            doc.trim()
        );
    }
    for (name, doc, value) in limits::STRINGS {
        let _ = writeln!(
            out,
            "\n/** {} */\nexport const {name} = '{value}'",
            doc.trim()
        );
    }
    out
}

fn country_list() -> String {
    let mut out = format!(
        "{MARKER}\n\n/** Country code to centroid latitude and longitude in tenths of a degree. */\nexport const COUNTRY_CENTROIDS: Record<string, readonly [number, number]> = {{\n"
    );
    for (code, lat, lng) in country_centroids::CENTROIDS {
        let _ = writeln!(out, "  {code}: [{lat}, {lng}],");
    }
    out.push_str("}\n");
    out
}

fn index(type_files: &[String]) -> String {
    let mut out = format!("{MARKER}\n");
    for file in type_files {
        let module = file.trim_end_matches(".ts");
        let _ = writeln!(out, "export type * from './{module}'");
    }
    for module in ["commands", "countries", "errors", "limits", "queries"] {
        let _ = writeln!(out, "export * from './{module}'");
    }
    out
}

fn schema_of<T: JsonSchema>(generator: &mut SchemaGenerator) -> Value {
    generator.subschema_for::<T>().to_value()
}

fn openapi(ops: &[&OperationInfo]) -> String {
    let mut generator = SchemaSettings::draft2020_12()
        .with(|s| {
            s.definitions_path = "/components/schemas".into();
            s.meta_schema = None;
        })
        .into_generator();

    let error = schema_of::<errors::ApiErrorBody>(&mut generator);
    let command_key = schema_of::<envelope::CommandKey>(&mut generator);
    let command_meta = schema_of::<envelope::CommandMeta>(&mut generator);
    let snapshot_meta = schema_of::<envelope::SnapshotMeta>(&mut generator);
    schema_of::<config::RuntimeConfig>(&mut generator);

    let mut paths = Map::new();
    for op in ops {
        let args = (op.args.schema)(&mut generator).to_value();
        let result = (op.result.schema)(&mut generator).to_value();
        let mut security = match op.access {
            Access::Anonymous => Vec::new(),
            Access::Person => vec![json!({ "session": [] })],
        };
        if op.policy.key_grantable {
            security.push(json!({ "apiKey": [] }));
        }
        if op.policy.share != ShareReach::None {
            security.push(json!({ "share": [] }));
        }
        let responses = json!({
            "200": { "description": "Success", "content": { "application/json": { "schema": {
                "allOf": [if op.kind == Kind::Command { &command_meta } else { &snapshot_meta }, result]
            } } } },
            "default": { "description": "Typed API error", "content": { "application/json": { "schema": error } } },
        });
        let summary = op.summary.trim();

        let (path, item) = match op.kind {
            Kind::Command => (
                format!("/api/commands/{}", op.name),
                json!({ "post": {
                    "operationId": op.name,
                    "description": summary,
                    "security": security,
                    "parameters": [{
                        "name": limits::REQUEST_MARKER_HEADER,
                        "in": "header",
                        "required": true,
                        "schema": { "const": limits::REQUEST_MARKER_VALUE },
                    }],
                    "requestBody": { "required": true, "content": { "application/json": { "schema": {
                        "allOf": [command_key, args]
                    } } } },
                    "responses": responses,
                } }),
            ),
            Kind::Query => (
                format!("/api/queries/{}", op.name),
                json!({
                    "get": {
                        "operationId": op.name,
                        "description": summary,
                        "security": security,
                        "parameters": query_parameters(&generator, &args),
                        "responses": responses,
                    },
                    "post": {
                        "operationId": format!("{}.post", op.name),
                        "description": format!("{summary}\n\nThe same query with its arguments as a JSON object body."),
                        "security": security,
                        "requestBody": { "required": true, "content": { "application/json": { "schema": args } } },
                        "responses": responses,
                    },
                }),
            ),
        };
        paths.insert(path, item);
    }

    let document = json!({
        "openapi": "3.1.0",
        "info": {
            "title": "Holocron dashboard API",
            "version": env!("CARGO_PKG_VERSION"),
            "description": "Generated from the operation registry in crates/protocol. Commands need the request marker header and a same-origin Origin, unless sent with an API key.",
        },
        "paths": paths,
        "components": {
            "schemas": generator.take_definitions(true),
            "securitySchemes": {
                "session": { "type": "apiKey", "in": "cookie", "name": "holocron_session" },
                "apiKey": { "type": "http", "scheme": "bearer", "description": "A scoped API key. Reaches only the operations and sites in its grants." },
                "share": { "type": "http", "scheme": "share", "description": "`Authorization: Share <token>`. Reaches only the share's operations, sites and limits." }
            },
        },
    });
    let mut text = serde_json::to_string_pretty(&document).expect("OpenAPI document serializes");
    text.push('\n');
    text
}

/// Query arguments travel as query-string values, one parameter per property.
fn query_parameters(generator: &SchemaGenerator, args: &Value) -> Value {
    let Some(name) = args
        .get("$ref")
        .and_then(Value::as_str)
        .and_then(|r| r.rsplit('/').next())
    else {
        return json!([]);
    };
    let Some(definition) = generator.definitions().get(name) else {
        return json!([]);
    };
    let required: Vec<&str> = definition
        .get("required")
        .and_then(Value::as_array)
        .map(|list| list.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    let properties = definition.get("properties").and_then(Value::as_object);

    Value::Array(
        properties
            .into_iter()
            .flatten()
            .map(|(property, schema)| {
                json!({
                    "name": property,
                    "in": "query",
                    "required": required.contains(&property.as_str()),
                    "schema": schema,
                })
            })
            .collect(),
    )
}

/// Replaces the generated files in `web_dir` and writes the OpenAPI document.
pub fn write(output: &Output, web_dir: &Path, openapi_path: &Path) -> io::Result<()> {
    fs::create_dir_all(web_dir)?;
    for entry in fs::read_dir(web_dir)? {
        let path = entry?.path();
        if path.extension().is_some_and(|ext| ext == "ts") {
            fs::remove_file(path)?;
        }
    }
    for (name, contents) in &output.web {
        fs::write(web_dir.join(name), contents)?;
    }
    fs::write(openapi_path, &output.openapi)
}

/// Lists every difference between `output` and the committed files. Empty means no drift.
pub fn drift(output: &Output, web_dir: &Path, openapi_path: &Path) -> io::Result<Vec<String>> {
    let mut problems = Vec::new();
    let mut committed = BTreeMap::new();
    if web_dir.exists() {
        for entry in fs::read_dir(web_dir)? {
            let path = entry?.path();
            if path.extension().is_some_and(|ext| ext == "ts") {
                let name = path
                    .file_name()
                    .and_then(|n| n.to_str())
                    .unwrap_or_default()
                    .to_owned();
                committed.insert(name, fs::read_to_string(&path)?);
            }
        }
    }

    for (name, contents) in &output.web {
        match committed.get(name) {
            None => problems.push(format!("missing: {name}")),
            Some(existing) if existing != contents => problems.push(format!("changed: {name}")),
            Some(_) => {}
        }
    }
    for name in committed
        .keys()
        .filter(|name| !output.web.contains_key(*name))
    {
        problems.push(format!("stale: {name}"));
    }
    match fs::read_to_string(openapi_path) {
        Ok(existing) if existing == output.openapi => {}
        Ok(_) => problems.push(format!("changed: {}", openapi_path.display())),
        Err(_) => problems.push(format!("missing: {}", openapi_path.display())),
    }
    Ok(problems)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Output depends only on the registry, so two runs agree byte for byte.
    #[test]
    fn generation_is_deterministic() {
        let first = generate().unwrap();
        let second = generate().unwrap();
        assert_eq!(first.web, second.web);
        assert_eq!(first.openapi, second.openapi);
    }

    #[test]
    fn operation_names_are_unique() {
        let mut names: Vec<_> = operations::all()
            .map(|op| (op.name, op.kind == Kind::Command))
            .collect();
        let count = names.len();
        names.sort();
        names.dedup();
        assert_eq!(names.len(), count);
    }
}
